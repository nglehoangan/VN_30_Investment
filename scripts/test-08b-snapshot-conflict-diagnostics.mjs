import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {snapshotConflictDiagnostics} from './lib/08b-snapshot-conflict-diagnostics.mjs';
const p=JSON.parse(readFileSync('data/initialization-08b-remediation-work/execution-preview.json','utf8'));
const rows=snapshotConflictDiagnostics(p.snapshot,p.canonicalObservations,p.sourcePeriodWithdrawals);
const findings=JSON.parse(p.snapshot.manifest).findings.filter(f=>f.code==='BLOCKED_CONFLICT');
assert.equal(rows.length,findings.length);
const deposit=rows.find(r=>r.requirement.itemId==='BANK_CUSTOMER_DEPOSITS'&&r.requirement.periodEnd==='2026-06-30'&&r.contexts.some(c=>c.ticker==='TCB'));
assert.ok(deposit);
assert.ok(deposit.values.includes('662447730000000'));
assert.ok(deposit.values.includes('697400000000000'));
assert.ok(new Set(deposit.contexts.map(c=>c.fiscalCalendarReference)).size>1);
const candidateTamper=structuredClone(JSON.parse(p.snapshot.manifest));
const finding=candidateTamper.findings.find(f=>f.code==='BLOCKED_CONFLICT');finding.candidates.pop();
assert.throws(()=>snapshotConflictDiagnostics({...p.snapshot,manifest:JSON.stringify(candidateTamper)},p.canonicalObservations,p.sourcePeriodWithdrawals));
assert.throws(()=>snapshotConflictDiagnostics(p.snapshot,p.canonicalObservations.filter(o=>o.id!==deposit.observationIds[0]),p.sourcePeriodWithdrawals));
console.log(JSON.stringify({status:'PASS',actualSelectorConflicts:rows.length,TCBRequiredDepositConflictRetained:true,negativeControls:2}));
