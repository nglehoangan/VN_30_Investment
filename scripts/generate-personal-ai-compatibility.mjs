function derive(source, target, transform) {
  const bytes = readFileSync(source, 'utf8');
  const replacements = [];
  const replace = (from, to, count = 1) => {
    const actual = bytesWorking.split(from).length - 1;
    if (actual !== count) throw Error(`Compatibility anchor drift in ${source}: expected ${count}, got ${actual}`);
    bytesWorking = bytesWorking.replaceAll(from, to); replacements.push({ from, to, count });
  };
  let bytesWorking = bytes;
  transform(replace);
  const header = `// GENERATED by scripts/generate-personal-ai-compatibility.mjs; do not edit.\n// Financial baseline ${source} SHA256 ${createHash('sha256').update(bytes).digest('hex')}.\n// Only versioned origin/provenance/namespace adaptations; financial formulas and gates unchanged.\n`;
  const result = header + bytesWorking;
  if (check) { if (readFileSync(target, 'utf8') !== result) throw Error(`Personal AI financial parity drift: ${target}`); }
  else writeFileSync(target, result);
  return { source, target, replacements: replacements.length };
}
